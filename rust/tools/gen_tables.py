"""Generate the Rust port's Unicode and HTML entity tables from Python.

Usage (from the repository root, with the Python version that generates
``conformance/``)::

    .venv/bin/python rust/tools/gen_tables.py

Writes two files:

- ``rust/src/unicode_tables.rs``: the code point sets behind Python's ``re``
  classes ``\\w``, ``\\d`` and ``\\s`` and the string predicates
  ``str.isdigit()``, ``str.isupper()``, ``str.islower()`` and ``str.isalpha()``
  (one character), as sorted
  inclusive ranges, plus the Unicode version they were taken from; the
  per-character mappings of ``str.lower()`` and ``str.upper()`` and the two
  sets their final-sigma rule consults (probed through ``str.lower()``); and
  ``_FOLD_TABLE`` of ``python/src/email_reply_extractor/_names.py``, read from
  the block between its ``BEGIN``/``END GENERATED FOLD TABLE`` markers;
- ``rust/src/html_entities.rs``: ``html.entities.html5`` (the HTML5 named
  character references used by ``html.unescape``), sorted by name.

The tables are taken from the running interpreter, so the Rust port follows
the Unicode database of the Python version that records the conformance data.
Standard library only.
"""

from __future__ import annotations

import ast
import pathlib
import re
import subprocess
import sys
import unicodedata
from html.entities import html5

RUST_SRC = pathlib.Path(__file__).resolve().parents[1] / "src"
NAMES_PY = (
    pathlib.Path(__file__).resolve().parents[2]
    / "python"
    / "src"
    / "email_reply_extractor"
    / "_names.py"
)

HEADER = """\
// Generated by rust/tools/gen_tables.py from Python {version}
// (Unicode {unicode}). Do not edit by hand; rerun the script instead.
"""


def ranges(pred) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(sys.maxunicode + 2):
        ok = cp <= sys.maxunicode and not 0xD800 <= cp <= 0xDFFF and pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def emit_ranges(name: str, doc: str, rs: list[tuple[int, int]]) -> str:
    lines = [f"/// {doc}", f"pub(crate) const {name}: &[(u32, u32)] = &["]
    row: list[str] = []
    for lo, hi in rs:
        row.append(f"(0x{lo:X}, 0x{hi:X})")
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("];")
    return "\n".join(lines) + "\n"


def rust_str(s: str) -> str:
    out = []
    for ch in s:
        cp = ord(ch)
        if ch in '"\\':
            out.append("\\" + ch)
        elif 0x20 <= cp < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\u{{{cp:X}}}")
    return '"' + "".join(out) + '"'


def rust_char(ch: str) -> str:
    cp = ord(ch)
    if ch in "'\\":
        return "'\\" + ch + "'"
    if 0x20 <= cp < 0x7F:
        return f"'{ch}'"
    return f"'\\u{{{cp:X}}}'"


def emit_map(name: str, doc: str, pairs: list[tuple[str, str]]) -> str:
    lines = [f"/// {doc}", f"pub(crate) const {name}: &[(char, &str)] = &["]
    for key, value in sorted(pairs):
        lines.append(f"    ({rust_char(key)}, {rust_str(value)}),")
    lines.append("];")
    return "\n".join(lines) + "\n"


def case_map(method) -> list[tuple[str, str]]:
    out = []
    for cp in range(sys.maxunicode + 1):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        mapped = method(ch)
        if mapped != ch:
            out.append((ch, mapped))
    return out


def sigma_probe(ch: str) -> tuple[bool, bool]:
    """(case-ignorable, cased) as ``str.lower``'s final-sigma rule sees ``ch``.

    Before a capital sigma, the rule skips case-ignorable characters and then
    asks whether the character it stopped at is cased. After an "A" (cased),
    the sigma is final when ``ch`` is case-ignorable or cased; after a "1"
    (neither), only when ``ch`` is cased and not case-ignorable. Cased is
    consulted only for characters that are not case-ignorable, so the second
    probe is the cased set the port needs.
    """
    after_cased = ("A" + ch + "\u03a3").lower()[-1] == "\u03c2"
    after_other = ("1" + ch + "\u03a3").lower()[-1] == "\u03c2"
    return after_cased and not after_other, after_other


def fold_table() -> list[tuple[str, str]]:
    source = NAMES_PY.read_text(encoding="utf-8")
    begin = source.index("# BEGIN GENERATED FOLD TABLE")
    end = source.index("# END GENERATED FOLD TABLE")
    block = source[begin:end]
    literal = block[block.index("{") : block.rindex("}") + 1]
    table = ast.literal_eval(literal)
    if not all(isinstance(k, str) and len(k) == 1 for k in table):
        raise SystemExit("_FOLD_TABLE keys must be single characters")
    return list(table.items())


def main() -> int:
    version = sys.version.split()[0]
    header = HEADER.format(version=version, unicode=unicodedata.unidata_version)
    word = re.compile(r"\w")
    digit = re.compile(r"\d")
    space = re.compile(r"\s")
    space_ranges = ranges(lambda c: space.match(c) is not None)
    if space_ranges != ranges(str.isspace):
        raise SystemExit("re \\s and str.isspace() differ; the port assumes they agree")

    parts = [
        header,
        "//! Code point sets with Python's semantics (see `pystr` and `pyre`).\n",
        emit_ranges(
            "PY_WORD",
            "Python `re` `\\w` for `str` patterns (`str.isalnum()` or `_`).",
            ranges(lambda c: word.match(c) is not None),
        ),
        emit_ranges(
            "PY_DECIMAL",
            "Python `re` `\\d` for `str` patterns (Unicode Nd).",
            ranges(lambda c: digit.match(c) is not None),
        ),
        emit_ranges("PY_SPACE", "Python `re` `\\s` and `str.isspace()`.", space_ranges),
        emit_ranges("PY_ISDIGIT", "Python `str.isdigit()` for one character.", ranges(str.isdigit)),
        emit_ranges("PY_ISUPPER", "Python `str.isupper()` for one character.", ranges(str.isupper)),
        emit_ranges("PY_ISLOWER", "Python `str.islower()` for one character.", ranges(str.islower)),
        emit_ranges("PY_ISALPHA", "Python `str.isalpha()` for one character.", ranges(str.isalpha)),
        emit_map(
            "PY_LOWER",
            "Python `str.lower()` for one character, where it changes the character"
            " (capital sigma maps to the non-final form here; see `pystr::lower`).",
            case_map(str.lower),
        ),
        emit_map(
            "PY_UPPER",
            "Python `str.upper()` for one character, where it changes the character.",
            case_map(str.upper),
        ),
        emit_ranges(
            "PY_CASE_IGNORABLE",
            "Case-ignorable characters, as `str.lower()`'s final-sigma rule sees them.",
            ranges(lambda c: sigma_probe(c)[0]),
        ),
        emit_ranges(
            "PY_CASED",
            "Cased characters that are not case-ignorable, as `str.lower()`'s"
            " final-sigma rule sees them.",
            ranges(lambda c: sigma_probe(c)[1]),
        ),
        emit_map(
            "FOLD_TABLE",
            "`_FOLD_TABLE` of `_names.py` (name folding after `str.lower()`), sorted.",
            fold_table(),
        ),
    ]
    (RUST_SRC / "unicode_tables.rs").write_text("\n".join(parts), encoding="utf-8")

    entity_lines = [
        header,
        "//! `html.entities.html5`: HTML5 named character references, sorted by name.\n",
        "/// `(name, replacement)` pairs; names include the trailing `;` where the",
        "/// standard has one, and the legacy names without it appear separately.",
        "pub(crate) const HTML5: &[(&str, &str)] = &[",
    ]
    for name in sorted(html5):
        entity_lines.append(f"    ({rust_str(name)}, {rust_str(html5[name])}),")
    entity_lines.append("];\n")
    (RUST_SRC / "html_entities.rs").write_text("\n".join(entity_lines), encoding="utf-8")
    # Leave both files in ``cargo fmt`` form so that ``cargo fmt --check`` passes.
    subprocess.run(
        ["rustfmt", "--edition", "2021", "unicode_tables.rs", "html_entities.rs"],
        cwd=RUST_SRC,
        check=True,
    )
    print(f"wrote unicode_tables.rs and html_entities.rs ({len(html5)} entities)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
