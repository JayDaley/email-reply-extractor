"""Generate the Rust port's Unicode and HTML entity tables from Python.

Usage (from the repository root, with the Python version that generates
``conformance/``)::

    .venv/bin/python rust/tools/gen_tables.py

Writes two files:

- ``rust/src/unicode_tables.rs``: the code point sets behind Python's ``re``
  classes ``\\w``, ``\\d`` and ``\\s`` and the string predicates
  ``str.isdigit()`` and ``str.isupper()`` (one character), as sorted
  inclusive ranges, plus the Unicode version they were taken from;
- ``rust/src/html_entities.rs``: ``html.entities.html5`` (the HTML5 named
  character references used by ``html.unescape``), sorted by name.

The tables are taken from the running interpreter, so the Rust port follows
the Unicode database of the Python version that records the conformance data.
Standard library only.
"""

from __future__ import annotations

import pathlib
import re
import subprocess
import sys
import unicodedata
from html.entities import html5

RUST_SRC = pathlib.Path(__file__).resolve().parents[1] / "src"

HEADER = """\
// Generated by rust/tools/gen_tables.py from Python {version}
// (Unicode {unicode}). Do not edit by hand; rerun the script instead.
"""


def ranges(pred) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(sys.maxunicode + 2):
        ok = cp <= sys.maxunicode and not 0xD800 <= cp <= 0xDFFF and pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def emit_ranges(name: str, doc: str, rs: list[tuple[int, int]]) -> str:
    lines = [f"/// {doc}", f"pub(crate) const {name}: &[(u32, u32)] = &["]
    row: list[str] = []
    for lo, hi in rs:
        row.append(f"(0x{lo:X}, 0x{hi:X})")
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("];")
    return "\n".join(lines) + "\n"


def rust_str(s: str) -> str:
    out = []
    for ch in s:
        cp = ord(ch)
        if ch in '"\\':
            out.append("\\" + ch)
        elif 0x20 <= cp < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\u{{{cp:X}}}")
    return '"' + "".join(out) + '"'


def main() -> int:
    version = sys.version.split()[0]
    header = HEADER.format(version=version, unicode=unicodedata.unidata_version)
    word = re.compile(r"\w")
    digit = re.compile(r"\d")
    space = re.compile(r"\s")
    space_ranges = ranges(lambda c: space.match(c) is not None)
    if space_ranges != ranges(str.isspace):
        raise SystemExit("re \\s and str.isspace() differ; the port assumes they agree")

    parts = [
        header,
        "//! Code point sets with Python's semantics (see `pystr` and `pyre`).\n",
        emit_ranges(
            "PY_WORD",
            "Python `re` `\\w` for `str` patterns (`str.isalnum()` or `_`).",
            ranges(lambda c: word.match(c) is not None),
        ),
        emit_ranges(
            "PY_DECIMAL",
            "Python `re` `\\d` for `str` patterns (Unicode Nd).",
            ranges(lambda c: digit.match(c) is not None),
        ),
        emit_ranges("PY_SPACE", "Python `re` `\\s` and `str.isspace()`.", space_ranges),
        emit_ranges("PY_ISDIGIT", "Python `str.isdigit()` for one character.", ranges(str.isdigit)),
        emit_ranges("PY_ISUPPER", "Python `str.isupper()` for one character.", ranges(str.isupper)),
    ]
    (RUST_SRC / "unicode_tables.rs").write_text("\n".join(parts), encoding="utf-8")

    entity_lines = [
        header,
        "//! `html.entities.html5`: HTML5 named character references, sorted by name.\n",
        "/// `(name, replacement)` pairs; names include the trailing `;` where the",
        "/// standard has one, and the legacy names without it appear separately.",
        "pub(crate) const HTML5: &[(&str, &str)] = &[",
    ]
    for name in sorted(html5):
        entity_lines.append(f"    ({rust_str(name)}, {rust_str(html5[name])}),")
    entity_lines.append("];\n")
    (RUST_SRC / "html_entities.rs").write_text("\n".join(entity_lines), encoding="utf-8")
    # Leave both files in ``cargo fmt`` form so that ``cargo fmt --check`` passes.
    subprocess.run(
        ["rustfmt", "--edition", "2021", "unicode_tables.rs", "html_entities.rs"],
        cwd=RUST_SRC,
        check=True,
    )
    print(f"wrote unicode_tables.rs and html_entities.rs ({len(html5)} entities)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
