"""Generate the TypeScript port's Unicode and HTML-entity tables from Python.

Usage, from the repository root, with the Python that generates
``conformance/`` (3.14)::

    python typescript/tools/generate_tables.py

Writes ``typescript/src/unicodeTables.ts`` and ``typescript/src/entities.ts``.
The tables record the behaviour of the Python standard library that the
reference implementation depends on, so the port reproduces it on every
Node.js version regardless of the Unicode version of the JavaScript engine:

- the ``str.isspace()`` set (also ``re``'s ``\\s``);
- ``re``'s Unicode ``\\w`` and ``\\d`` sets, and ``[^\\W\\d_]``;
- the ``str.isdigit()`` and single-character ``str.isupper()`` sets;
- ``re.IGNORECASE`` equivalence classes for the cased characters the
  patterns use;
- ``html.entities.html5``, the named character references used by
  ``html.unescape``.

Standard library only.
"""

from __future__ import annotations

import html.entities
import json
import pathlib
import re
import sys
import unicodedata

OUT = pathlib.Path(__file__).resolve().parents[1] / "src"

HEADER = (
    "// Generated by tools/generate_tables.py from Python {py} (Unicode {uni}).\n"
    "// Do not edit by hand.\n"
)


def _ranges(pred) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(0x110000):
        ok = False if 0xD800 <= cp <= 0xDFFF else pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def _esc(cp: int) -> str:
    return "\\\\u{%x}" % cp


def _class_body(ranges: list[tuple[int, int]]) -> str:
    parts = []
    for a, b in ranges:
        parts.append(_esc(a) if a == b else f"{_esc(a)}-{_esc(b)}")
    return "".join(parts)


def _ranges_array(ranges: list[tuple[int, int]]) -> str:
    return "[" + ",".join(f"[0x{a:x},0x{b:x}]" for a, b in ranges) + "]"


def unicode_tables() -> str:
    word = re.compile(r"\w")
    digit = re.compile(r"\d")
    letter = re.compile(r"[^\W\d_]")
    space = re.compile(r"\s")
    ws = _ranges(str.isspace)
    assert ws == _ranges(lambda c: bool(space.match(c)))

    # re.IGNORECASE equivalence classes for the cased characters of Latin-1
    # Supplement, Latin Extended-A and ASCII (the patterns use no others).
    ci: dict[str, list[int]] = {}
    candidates = [chr(c) for c in range(0x41, 0x7B) if chr(c).isalpha()]
    candidates += [chr(c) for c in range(0xC0, 0x180) if chr(c).isalpha()]
    for ch in candidates:
        pat = re.compile(re.escape(ch), re.IGNORECASE)
        ci[ch] = [
            cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF and pat.fullmatch(chr(cp))
        ]

    lines = [HEADER.format(py=sys.version.split()[0], uni=unicodedata.unidata_version)]
    lines.append("/** Class body: the `str.isspace()` set (also `re`'s `\\s`). */")
    lines.append(f'export const SPACE_CLASS: string = "{_class_body(ws)}";')
    lines.append("/** Class body: `re`'s Unicode `\\w`. */")
    lines.append(
        f'export const WORD_CLASS: string = "{_class_body(_ranges(lambda c: bool(word.match(c))))}";'
    )
    lines.append("/** Class body: `re`'s Unicode `\\d`. */")
    lines.append(
        f'export const DIGIT_CLASS: string = "{_class_body(_ranges(lambda c: bool(digit.match(c))))}";'
    )
    lines.append("/** Class body: `re`'s `[^\\W\\d_]`. */")
    lines.append(
        f'export const LETTER_CLASS: string = "{_class_body(_ranges(lambda c: bool(letter.match(c))))}";'
    )
    lines.append("/** Code-point ranges for which `str.isdigit()` is true. */")
    lines.append(
        f"export const ISDIGIT_RANGES: readonly (readonly [number, number])[] = "
        f"{_ranges_array(_ranges(str.isdigit))};"
    )
    lines.append("/** Code-point ranges for which single-character `str.isupper()` is true. */")
    lines.append(
        f"export const ISUPPER_RANGES: readonly (readonly [number, number])[] = "
        f"{_ranges_array(_ranges(str.isupper))};"
    )
    lines.append(
        "/** `re.IGNORECASE` equivalents (code points) of the cased ASCII and Latin-1/Latin"
        " Extended-A letters. */"
    )
    lines.append(
        "export const IGNORECASE_EQUIVALENTS: Readonly<Record<string, readonly number[]>> = {"
    )
    for ch, cps in ci.items():
        lines.append(
            f"  {json.dumps(ch, ensure_ascii=True)}: [{', '.join(f'0x{c:x}' for c in cps)}],"
        )
    lines.append("};")
    return "\n".join(lines) + "\n"


def entities() -> str:
    lines = [HEADER.format(py=sys.version.split()[0], uni=unicodedata.unidata_version)]
    lines.append("/** `html.entities.html5`: named character reference to replacement text. */")
    lines.append("export const HTML5_ENTITIES: ReadonlyMap<string, string> = new Map([")
    for name, value in html.entities.html5.items():
        lines.append(
            f"  [{json.dumps(name, ensure_ascii=True)}, {json.dumps(value, ensure_ascii=True)}],"
        )
    lines.append("]);")
    return "\n".join(lines) + "\n"


def main() -> int:
    (OUT / "unicodeTables.ts").write_text(unicode_tables(), encoding="utf-8")
    (OUT / "entities.ts").write_text(entities(), encoding="utf-8")
    print(f"wrote {OUT / 'unicodeTables.ts'} and {OUT / 'entities.ts'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
