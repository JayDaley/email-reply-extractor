"""Generate the TypeScript port's Unicode and HTML-entity tables from Python.

Usage, from the repository root, with the Python that generates
``conformance/`` (3.14)::

    python typescript/tools/generate_tables.py

Writes ``typescript/src/unicodeTables.ts`` and ``typescript/src/entities.ts``.
The tables record the behaviour of the Python standard library that the
reference implementation depends on, so the port reproduces it on every
Node.js version regardless of the Unicode version of the JavaScript engine:

- the ``str.isspace()`` set (also ``re``'s ``\\s``);
- ``re``'s Unicode ``\\w`` and ``\\d`` sets, and ``[^\\W\\d_]``;
- the ``str.isdigit()`` and single-character ``str.isupper()`` sets;
- ``re.IGNORECASE`` equivalence classes for the cased characters the
  patterns use;
- ``str.lower()`` (the full lowercase mapping, with the Final_Sigma context
  rule), and the code points ``str.upper()`` changes;
- ``html.entities.html5``, the named character references used by
  ``html.unescape``;
- the literal name-folding table of ``_names.py`` (``src/foldTable.ts``),
  copied entry for entry from the block between its BEGIN/END GENERATED FOLD
  TABLE markers.

Standard library only.
"""

from __future__ import annotations

import ast
import html.entities
import json
import pathlib
import re
import sys
import unicodedata

OUT = pathlib.Path(__file__).resolve().parents[1] / "src"
NAMES_PY = (
    pathlib.Path(__file__).resolve().parents[2]
    / "python"
    / "src"
    / "email_reply_extractor"
    / "_names.py"
)

HEADER = (
    "// Generated by tools/generate_tables.py from Python {py} (Unicode {uni}).\n"
    "// Do not edit by hand.\n"
)


def _ranges(pred) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(0x110000):
        ok = False if 0xD800 <= cp <= 0xDFFF else pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def _esc(cp: int) -> str:
    return "\\\\u{%x}" % cp


def _class_body(ranges: list[tuple[int, int]]) -> str:
    parts = []
    for a, b in ranges:
        parts.append(_esc(a) if a == b else f"{_esc(a)}-{_esc(b)}")
    return "".join(parts)


def _ranges_array(ranges: list[tuple[int, int]]) -> str:
    return "[" + ",".join(f"[0x{a:x},0x{b:x}]" for a, b in ranges) + "]"


def _lower_runs() -> tuple[list[tuple[int, int, int, int]], dict[int, str]]:
    """``chr(c).lower()`` where it differs from ``chr(c)``, without the sigma rule.

    Single-code-point results as runs ``(first, last, step, delta)``: every
    ``c = first + k * step <= last`` lowercases to ``c + delta``. Results of
    more than one code point are returned separately.
    """
    single: list[tuple[int, int]] = []
    multi: dict[int, str] = {}
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        low = chr(cp).lower()
        if low == chr(cp):
            continue
        if len(low) == 1:
            single.append((cp, ord(low) - cp))
        else:
            multi[cp] = low
    runs: list[tuple[int, int, int, int]] = []
    for cp, delta in single:
        if runs:
            first, last, step, d = runs[-1]
            if d == delta and (
                (first == last and cp - last in (1, 2)) or (first != last and cp - last == step)
            ):
                runs[-1] = (first, cp, cp - last if first == last else step, d)
                continue
        runs.append((cp, cp, 1, delta))
    return runs, multi


def _sigma_context() -> tuple[list[tuple[int, int]], list[tuple[int, int]]]:
    """The Final_Sigma context classes of ``str.lower``, read from its behaviour.

    ``"a\u03a3" + c`` keeps a non-final sigma exactly when ``c`` is cased and
    not case-ignorable; ``"a\u03a3" + c + "a"`` does when ``c`` is cased or
    case-ignorable. Those two classes are all the context rule reads.
    """

    def non_final(text: str) -> bool:
        return "\u03c3" in text.lower()

    cased = _ranges(lambda c: non_final("a\u03a3" + c))
    ignorable = _ranges(lambda c: non_final("a\u03a3" + c + "a") and not non_final("a\u03a3" + c))
    return cased, ignorable


def unicode_tables() -> str:
    word = re.compile(r"\w")
    digit = re.compile(r"\d")
    letter = re.compile(r"[^\W\d_]")
    space = re.compile(r"\s")
    ws = _ranges(str.isspace)
    assert ws == _ranges(lambda c: bool(space.match(c)))
    # re's \w is str.isalnum() plus "_" (the port's str.isalnum() test relies on it).
    assert _ranges(lambda c: bool(word.match(c))) == _ranges(lambda c: c.isalnum() or c == "_")

    # re.IGNORECASE equivalence classes for the cased characters of Latin-1
    # Supplement, Latin Extended-A, ASCII and basic Cyrillic (the patterns use no others).
    ci: dict[str, list[int]] = {}
    candidates = [chr(c) for c in range(0x41, 0x7B) if chr(c).isalpha()]
    candidates += [chr(c) for c in range(0xC0, 0x180) if chr(c).isalpha()]
    # Basic Cyrillic, for the speech verbs of the generic attribution rule.
    candidates += [chr(c) for c in range(0x410, 0x450) if chr(c).isalpha()]
    for ch in candidates:
        pat = re.compile(re.escape(ch), re.IGNORECASE)
        ci[ch] = [
            cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF and pat.fullmatch(chr(cp))
        ]

    lines = [HEADER.format(py=sys.version.split()[0], uni=unicodedata.unidata_version)]
    lines.append("/** Class body: the `str.isspace()` set (also `re`'s `\\s`). */")
    lines.append(f'export const SPACE_CLASS: string = "{_class_body(ws)}";')
    lines.append("/** Class body: `re`'s Unicode `\\w`. */")
    lines.append(
        f'export const WORD_CLASS: string = "{_class_body(_ranges(lambda c: bool(word.match(c))))}";'
    )
    lines.append("/** Class body: `re`'s Unicode `\\d`. */")
    lines.append(
        f'export const DIGIT_CLASS: string = "{_class_body(_ranges(lambda c: bool(digit.match(c))))}";'
    )
    lines.append("/** Class body: `re`'s `[^\\W\\d_]`. */")
    lines.append(
        f'export const LETTER_CLASS: string = "{_class_body(_ranges(lambda c: bool(letter.match(c))))}";'
    )
    lines.append("/** Code-point ranges for which `str.isdigit()` is true. */")
    lines.append(
        f"export const ISDIGIT_RANGES: readonly (readonly [number, number])[] = "
        f"{_ranges_array(_ranges(str.isdigit))};"
    )
    lines.append("/** Code-point ranges for which single-character `str.isupper()` is true. */")
    lines.append(
        f"export const ISUPPER_RANGES: readonly (readonly [number, number])[] = "
        f"{_ranges_array(_ranges(str.isupper))};"
    )
    lines.append("/** Code-point ranges for which single-character `str.islower()` is true. */")
    lines.append(
        f"export const ISLOWER_RANGES: readonly (readonly [number, number])[] = "
        f"{_ranges_array(_ranges(str.islower))};"
    )
    lines.append("/** Code-point ranges for which single-character `str.isalpha()` is true. */")
    lines.append(
        f"export const ISALPHA_RANGES: readonly (readonly [number, number])[] = "
        f"{_ranges_array(_ranges(str.isalpha))};"
    )
    runs, multi = _lower_runs()
    lines.append(
        "/** `str.lower()` of single code points, as runs [first, last, step, delta]: every"
        " `first + k * step <= last` maps to itself plus `delta` (Final_Sigma aside). */"
    )
    lines.append(
        "export const LOWER_RUNS: readonly (readonly [number, number, number, number])[] = ["
        + ",".join(f"[0x{a:x},0x{b:x},{st},{d}]" for a, b, st, d in runs)
        + "];"
    )
    lines.append("/** `str.lower()` results of more than one code point. */")
    lines.append(
        "export const LOWER_EXPANSIONS: Readonly<Record<string, string>> = {"
        + ", ".join(
            f"{json.dumps(chr(c), ensure_ascii=True)}: {json.dumps(v, ensure_ascii=True)}"
            for c, v in multi.items()
        )
        + "};"
    )
    lines.append("/** Code-point ranges for which single-character `str.upper()` differs. */")
    lines.append(
        f"export const UPPER_CHANGES_RANGES: readonly (readonly [number, number])[] = "
        f"{_ranges_array(_ranges(lambda c: c.upper() != c))};"
    )
    cased, ignorable = _sigma_context()
    lines.append(
        "/** Final_Sigma context of `str.lower()`: cased code points that are not"
        " case-ignorable. */"
    )
    lines.append(
        f"export const SIGMA_CASED_RANGES: readonly (readonly [number, number])[] = "
        f"{_ranges_array(cased)};"
    )
    lines.append("/** Final_Sigma context of `str.lower()`: case-ignorable code points. */")
    lines.append(
        f"export const SIGMA_IGNORABLE_RANGES: readonly (readonly [number, number])[] = "
        f"{_ranges_array(ignorable)};"
    )
    lines.append(
        "/** `re.IGNORECASE` equivalents (code points) of the cased ASCII and Latin-1/Latin"
        " Extended-A and basic Cyrillic letters. */"
    )
    lines.append(
        "export const IGNORECASE_EQUIVALENTS: Readonly<Record<string, readonly number[]>> = {"
    )
    for ch, cps in ci.items():
        lines.append(
            f"  {json.dumps(ch, ensure_ascii=True)}: [{', '.join(f'0x{c:x}' for c in cps)}],"
        )
    lines.append("};")
    return "\n".join(lines) + "\n"


def entities() -> str:
    lines = [HEADER.format(py=sys.version.split()[0], uni=unicodedata.unidata_version)]
    lines.append("/** `html.entities.html5`: named character reference to replacement text. */")
    lines.append("export const HTML5_ENTITIES: ReadonlyMap<string, string> = new Map([")
    for name, value in html.entities.html5.items():
        lines.append(
            f"  [{json.dumps(name, ensure_ascii=True)}, {json.dumps(value, ensure_ascii=True)}],"
        )
    lines.append("]);")
    return "\n".join(lines) + "\n"


def fold_table() -> str:
    """``_FOLD_TABLE`` of ``_names.py``, read from its generated block."""
    source = NAMES_PY.read_text(encoding="utf-8")
    begin = source.index("# BEGIN GENERATED FOLD TABLE")
    end = source.index("# END GENERATED FOLD TABLE")
    block = source[begin:end]
    table = ast.literal_eval(block[block.index("{") : block.rindex("}") + 1])
    assert all(len(k) == 1 for k in table)
    lines = [
        "// Generated by tools/generate_tables.py from the GENERATED FOLD TABLE block of\n"
        "// python/src/email_reply_extractor/_names.py. Do not edit by hand.\n"
    ]
    lines.append(
        f"/** `_FOLD_TABLE` of `_names.py` ({len(table)} entries): one character to its"
        " replacement. */"
    )
    lines.append("export const FOLD_TABLE: ReadonlyMap<string, string> = new Map([")
    for key, value in table.items():
        lines.append(
            f"  [{json.dumps(key, ensure_ascii=True)}, {json.dumps(value, ensure_ascii=True)}],"
        )
    lines.append("]);")
    return "\n".join(lines) + "\n"


def main() -> int:
    (OUT / "unicodeTables.ts").write_text(unicode_tables(), encoding="utf-8")
    (OUT / "entities.ts").write_text(entities(), encoding="utf-8")
    (OUT / "foldTable.ts").write_text(fold_table(), encoding="utf-8")
    print(f"wrote {OUT / 'unicodeTables.ts'}, {OUT / 'entities.ts'} and {OUT / 'foldTable.ts'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
