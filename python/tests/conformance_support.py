"""Shared code for the language-neutral conformance data under ``conformance/``.

The data is generated by ``python/tools/conformance.py`` (``make vectors``) and
checked by ``test_conformance.py`` and ``test_extraction_version.py``. The file
formats are specified in ``conformance/README.md``; this module is the single
Python implementation of them:

- :func:`encode` turns a reference result (a dataclass, list, string, bool,
  int or ``None``) into its JSON value;
- :func:`corpus_entry` builds one ``corpus.json`` entry from a fixture;
- :func:`digest_of_entries` computes the corpus digest from ``corpus.json``
  entries alone, the way a port computes it;
- :func:`dumps` serializes with the escaping rules that keep invisible
  characters visible in a diff and round-trip exactly.
"""

from __future__ import annotations

import dataclasses
import hashlib
import json
import pathlib
import re
from typing import Any

from corpus import ALL_STEMS, REPO_ROOT, expected_text, fixture_bodies

from email_reply_extractor import (
    clean_for_scoring,
    extract_new_text,
    html_to_text,
    split_html_parts,
)

#: The version of the conformance file formats. Bump it when a file's schema
#: changes so a port's harness can refuse data it does not understand.
FORMAT = 1

CONFORMANCE_DIR = REPO_ROOT / "conformance"
CORPUS_PATH = CONFORMANCE_DIR / "corpus.json"
DIGEST_PATH = CONFORMANCE_DIR / "digest.json"
VECTORS_DIR = CONFORMANCE_DIR / "vectors"


# --- value encoding -----------------------------------------------------------


def encode(value: Any) -> Any:
    """Return the JSON value of a reference argument or result.

    Dataclasses become objects with their fields in declaration order; lists
    and tuples become arrays; ``None``, booleans, integers and strings map
    directly. Anything else is a programming error in the recorder and raises.
    """
    if value is None or isinstance(value, (bool, int, str)):
        return value
    if dataclasses.is_dataclass(value) and not isinstance(value, type):
        return {f.name: encode(getattr(value, f.name)) for f in dataclasses.fields(value)}
    if isinstance(value, (list, tuple)):
        return [encode(v) for v in value]
    raise TypeError(f"no JSON encoding for {type(value).__name__}: {value!r}")


def error_name(exc: BaseException) -> str:
    """The recorded name of an exception a reference function raised.

    The class name, except that :class:`re.error` is always recorded under its
    Python 3.13+ name ``PatternError``, so the data does not depend on the
    Python version that generated or replays it.
    """
    if isinstance(exc, re.error):
        return "PatternError"
    return type(exc).__name__


# --- serialization ------------------------------------------------------------

#: Characters written as ``\\uXXXX`` escapes instead of raw: DEL and the C1
#: controls, the no-break and other non-ASCII spaces, the soft hyphen, the
#: zero-width and bidi format characters, the line and paragraph separators,
#: the byte-order mark, the interlinear annotation and specials block and the
#: tag characters. The escaped form loads back identically
#: and keeps such characters visible in a diff. The set is a fixed list rather
#: than a Unicode-category lookup, so the output does not depend on the Unicode
#: database of the generating Python.
_ESCAPE_RE = re.compile(
    "["
    "\x7f-\xa0\xad\u034f\u061c\u115f\u1160\u1680\u180e"
    "\u2000-\u200f\u2028-\u202f\u205f-\u206f\u3000\u3164"
    "\ufe00-\ufe0f\ufeff\uffa0\ufff0-\ufffb"
    "\U000e0000-\U000e007f"
    "]"
)


def _escape_char(match: re.Match[str]) -> str:
    cp = ord(match.group(0))
    if cp <= 0xFFFF:
        return f"\\u{cp:04x}"
    cp -= 0x10000
    return f"\\u{0xD800 + (cp >> 10):04x}\\u{0xDC00 + (cp & 0x3FF):04x}"


def dumps(obj: Any) -> str:
    """Serialize ``obj`` as the conformance files are written.

    UTF-8 text, keys in insertion order, one-space indentation, a trailing
    newline. ASCII controls below U+0020 are escaped by :mod:`json` itself;
    the characters matched by :data:`_ESCAPE_RE` are escaped here. The result
    is verified to load back equal to ``obj``.
    """
    text = json.dumps(obj, ensure_ascii=False, indent=1) + "\n"
    # A lone surrogate cannot be encoded as UTF-8, and several JSON parsers
    # (serde_json among them) reject its escaped form; fail here instead.
    text.encode("utf-8")
    text = _ESCAPE_RE.sub(_escape_char, text)
    if json.loads(text) != obj:
        raise AssertionError("conformance JSON does not round-trip")
    return text


def load(path: pathlib.Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


# --- corpus -------------------------------------------------------------------


def corpus_entry(stem: str) -> dict[str, Any]:
    """Return the ``corpus.json`` entry for one fixture (schema in the README)."""
    body, html_body = fixture_bodies(stem)
    stage1 = extract_new_text(body, html_body=html_body)
    stage2 = clean_for_scoring(stage1.text)
    entry: dict[str, Any] = {
        "stem": stem,
        "body": body,
        "html_body": html_body,
        "expected": expected_text(stem),
        "extract_new_text": encode(stage1),
        "clean_for_scoring": encode(stage2),
        "html_to_text": None,
        "split_html_parts": None,
        "html_signature_text": None,
        "clean_for_scoring_with_html_signature": None,
    }
    if html_body is not None:
        parts = split_html_parts(html_body)
        hint = parts.signature_text or None
        entry["html_to_text"] = html_to_text(html_body)
        entry["split_html_parts"] = encode(parts)
        entry["html_signature_text"] = hint
        entry["clean_for_scoring_with_html_signature"] = encode(
            clean_for_scoring(stage1.text, hint)
        )
    return entry


def corpus_entries() -> list[dict[str, Any]]:
    return [corpus_entry(stem) for stem in ALL_STEMS]


def digest_of_entries(entries: list[dict[str, Any]]) -> str:
    """The corpus digest, computed from ``corpus.json`` entries alone.

    For each entry, in order: the stem, the stage-1-then-stage-2 composite
    (``clean_for_scoring.text``), stage 1's ``text`` and stage 1's ``method``.
    Each field is UTF-8 encoded and preceded by its byte length in ASCII
    decimal and a colon, so no combination of contents can imitate a
    different split.
    """
    digest = hashlib.sha256()
    for entry in entries:
        fields = (
            entry["stem"],
            entry["clean_for_scoring"]["text"],
            entry["extract_new_text"]["text"],
            entry["extract_new_text"]["method"],
        )
        for field in fields:
            encoded = field.encode("utf-8")
            digest.update(f"{len(encoded)}:".encode("ascii"))
            digest.update(encoded)
    return digest.hexdigest()
